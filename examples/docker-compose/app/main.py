import os
import time
from pathlib import Path

import requests
import urllib3
from zipreport import ZipReport
from zipreport.report import ReportFileLoader

# Suppress SSL warnings for self-signed certs
urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)

ZIPREPORT_URL = os.getenv("ZIPREPORT_URL", "http://127.0.0.1:6543")
ZIPREPORT_KEY = os.getenv("ZIPREPORT_KEY", "somePassword")

REPORT_PATH = Path("/reports/simple")
OUTPUT_PATH = Path("/output/report.pdf")


def wait_for_server(url, max_retries=30, delay=2):
    """Wait for zipreport-server to become available."""
    for attempt in range(1, max_retries + 1):
        try:
            r = requests.get(url, verify=False, timeout=5)
            # Server is ready if it responds (even with 401 unauthorized)
            if r.status_code in (200, 401, 404):
                print("zipreport-server is ready")
                return True
        except requests.exceptions.ConnectionError:
            pass
        except Exception as e:
            print(f"Health check error: {e}")
        print(f"Waiting for zipreport-server (attempt {attempt}/{max_retries})...")
        time.sleep(delay)
    return False


def main():
    if not REPORT_PATH.exists():
        print(f"Report template not found at {REPORT_PATH}")
        print("Ensure the reports volume is mounted correctly.")
        exit(1)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    if not wait_for_server(ZIPREPORT_URL):
        print("zipreport-server did not become available, exiting.")
        exit(1)

    report = ReportFileLoader.load(REPORT_PATH)

    report_data = {
        "title": "Docker Compose Example Report",
        "color_list": ["red", "blue", "green"],
        "description": "This PDF was generated by a containerized application using zipreport-server.",
    }

    result = ZipReport(ZIPREPORT_URL, ZIPREPORT_KEY).render_defaults(report, report_data)
    if not result.success:
        print("Error generating report:", result.error)
        exit(1)

    with open(OUTPUT_PATH, "wb") as f:
        f.write(result.report.read())

    print(f"Report generated successfully: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
